        <h1 class="h2 mb-3">O projektu</h1>
        <p class="lead">
            Zagreb Prijave je web aplikacija za prijavu komunalnih problema u Gradu Zagrebu,
            pregled radova na gradskoj infrastrukturi i stanja u prometu.
        </p>

        <div class="alert alert-warning">
