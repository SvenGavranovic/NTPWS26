        </div>

        <h2 class="h4 mt-4">Problem koji rješava</h2>
        <p>
            Građani često ne znaju kome prijaviti oštećen kolnik, neispravnu rasvjetu ili divlje odlagalište,
            a kad prijavu pošalju, ne vide što se s njom događa. Aplikacija prijavu vodi kroz jasne korake,
            od zaprimanja do provjere obavljenog posla, a svaka promjena statusa se bilježi.
        </p>

        <h2 class="h4 mt-4">Uloge</h2>
        <table class="table table-sm align-middle">
            <thead><tr><th>Uloga</th><th>Što može</th></tr></thead>
            <tbody>
                <tr><td>Posjetitelj</td><td>Čita vijesti, pregledava kartu, radove i promet</td></tr>
                <tr><td>Registrirani korisnik</td><td>Prijavljuje probleme s fotografijom i prati njihov status</td></tr>
                <tr><td>Radnik</td><td>Rješava dodijeljene zadatke i šalje ih na provjeru</td></tr>
                <tr><td>Urednik</td><td>Piše i uređuje vlastite vijesti</td></tr>
                <tr><td>Administrator</td><td>Upravlja sadržajem, korisnicima, zadacima i radovima</td></tr>
            </tbody>
        </table>

        <h2 class="h4 mt-4">Tehnologije</h2>
        <ul>
            <li>PHP 8 s vlastitom MVC strukturom (bez frameworka), MariaDB, PDO</li>
            <li>Bootstrap 5, JavaScript (Fetch API)</li>
            <li>Vlastiti REST API (JSON)</li>
            <li>Leaflet i OpenStreetMap za kartu, TomTom Traffic API za stanje u prometu</li>
        </ul>

        <h2 class="h4 mt-4">Korištenje AI alata</h2>
